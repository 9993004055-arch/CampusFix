CREATE DATABASE IF NOT EXISTS campus_fault_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE campus_fault_db;
CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL,
 username VARCHAR(40) NULL UNIQUE, email VARCHAR(190) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
 role ENUM('student','faculty','admin','repair_staff') NOT NULL DEFAULT 'student',
 is_active TINYINT(1) NOT NULL DEFAULT 1, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS reports (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, tracking_code VARCHAR(20) UNIQUE,
 user_id INT UNSIGNED NOT NULL, assigned_staff_id INT UNSIGNED NULL, title VARCHAR(150) NOT NULL, category VARCHAR(50) NOT NULL,
 department VARCHAR(100) NOT NULL, location VARCHAR(180) NOT NULL, description TEXT NOT NULL,
 priority ENUM('normal','urgent') NOT NULL DEFAULT 'normal', photo_path VARCHAR(255),
 status ENUM('Submitted','Accepted','In Progress','Completed','Declined') NOT NULL DEFAULT 'Submitted',
 admin_reason VARCHAR(1000), expected_days SMALLINT UNSIGNED, completion_note VARCHAR(1000),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id), FOREIGN KEY (assigned_staff_id) REFERENCES users(id) ON DELETE SET NULL, INDEX(status), INDEX(priority), INDEX(created_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS status_history (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, report_id INT UNSIGNED NOT NULL,
 changed_by INT UNSIGNED NULL, status VARCHAR(30) NOT NULL, note VARCHAR(1000),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (report_id) REFERENCES reports(id) ON DELETE CASCADE,
 FOREIGN KEY (changed_by) REFERENCES users(id) ON DELETE SET NULL, INDEX(report_id,created_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS notifications (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NOT NULL,
 report_id INT UNSIGNED NULL, message VARCHAR(1000) NOT NULL, is_read TINYINT(1) DEFAULT 0,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY (report_id) REFERENCES reports(id) ON DELETE SET NULL, INDEX(user_id,created_at)
) ENGINE=InnoDB;
